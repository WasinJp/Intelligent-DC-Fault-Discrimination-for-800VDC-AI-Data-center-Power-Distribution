function names = dcsim_rt_hil_params(shared, dt)
%DCSIM_RT_HIL_PARAMS  Create the tunable parameters of dcsim_rt_hil.slx in the base workspace as Simulink.Parameter
%   objects (storage class ExportedGlobal -> tunable in the generated code; ConfigurationDesk / ControlDesk list them by
%   name). Defaults = the design point: workload on at P0 = 0.5 P_rated with the tier-1 cadence of MODEL.md 5.1, no fault
%   armed, AO full scale 10 V, SYNC 20 us, breaker delay 20 us (the SSCB opening time of DEADLINE_STUDY), uvlo_tol 0.5
%   (step counting, the HIL setting), converter smoothing on (GB300-class ramp-rate front end; MODEL.md sweeps it 50/50,
%   so state the regime you demo with). 38 tunables (2026-10-16: conv_smooth added, review #7).
%   shared: params.json struct (load_case) for P_rated; dt: the model step [s].
%   Returns the parameter names grouped as the MATLAB Function block expects them (fp, wp, cp).
if nargin < 1 || isempty(shared), shared = struct('P_rated', 132e3); end
if nargin < 2 || isempty(dt), dt = 5e-6; end
P = shared.P_rated;

fp = { ...  % name            default        unit   description
 'fault_type',      0,            '-',  '0 none | 1 800 V branch | 2 48 V branch | 3 series arc'; ...
 'fault_Rf',        3.0,          'ohm','800 V fault resistance (1e-3 bolted .. 10 high-Z)'; ...
 'fault_Lf',        2e-6,         'H',  '800 V fault inductance (0.5e-6 .. 10e-6)'; ...
 'fault_Rf48',      20e-3,        'ohm','48 V fault resistance (0.5e-3 bolted .. 100e-3 high-Z)'; ...
 'fault_Lf48',      0.5e-6,       'H',  '48 V fault inductance (0.1e-6 .. 2e-6)'; ...
 'fault_Varc',      25.0,         'V',  'series arc voltage (15 .. 40), type 3 only'; ...
 'fault_mode',      0,            '-',  'inception: 0 now | 1 on the next tier-1 rising edge of the workload'; ...
 'fault_trigger',   0,            '-',  'ControlDesk trigger (0 -> 1 edge fires; OR-ed with FAULT_CMD input)'; ...
 'step_dP',         0,            'W',  'benign load step applied at the trigger (0.4*P_rated = check (i) step case; 0 = none)'; ...
 'step_ramp',       2e-3,         's',  'ramp time of the benign step'; ...
 'fault_arc_m',     0.15,         '-',  'series arc noise modulation (0.05 .. 0.25 of V_arc; 0 = DC only)'; ...
 'fault_arc_ramp',  0.5e-3,       's',  'series arc ignition ramp (0.1e-3 .. 2e-3)'};
wp = { ...
 'wl_on',           1,            '-',  'workload generator on (0 = constant P0)'; ...
 'wl_P0',           0.5 * P,      'W',  'idle / base GPU power'; ...
 'wl_dP1',          0.3 * P,      'W',  'tier-1 iteration amplitude (0.1 .. 0.8 P_rated)'; ...
 'wl_T1',           1.0,          's',  'tier-1 period (0.3 .. 3 s)'; ...
 'wl_duty1',        0.6,          '-',  'tier-1 compute-phase duty'; ...
 'wl_ramp1',        2e-3,         's',  'tier-1 edge ramp (0.5e-3 .. 10e-3)'; ...
 'wl_jit1',         0.01,         '-',  'tier-1 edge jitter, fraction of T1 (<= 0.02)'; ...
 'wl_dP2',          0.1 * P,      'W',  'tier-2 burst amplitude (0 = off; 0.05 .. 0.25 P_rated)'; ...
 'wl_T2',           0.08,         's',  'tier-2 period (0.02 .. 0.2 s)'; ...
 'wl_duty2',        0.5,          '-',  'tier-2 duty'; ...
 'wl_ramp2',        1e-3,         's',  'tier-2 edge ramp'; ...
 'wl_jit2',         0.01,         '-',  'tier-2 jitter, fraction of T2'; ...
 'wl_seed',         12345,        '-',  'xorshift32 seed (integer > 0); same seed = same workload'};
cp = { ...
 'hil_dt',          dt,           's',  'model step (must equal the solver FixedStep)'; ...
 'qs_dt_min',       1.5e-6,       's',  'quasi-static fault-branch rule floor (MODEL.md 0.4.4) - do not change'; ...
 'brk_delay',       20e-6,        's',  'SSCB opening time: TRIP seen high for round(brk_delay/dt) steps -> breaker opens on the step after (0 = the step TRIP is first seen)'; ...
 'uvlo_tol',        0.5,          '-',  'UVLO timers: 0.5 = step counting (HIL) | 0 = Python core float accumulation'; ...
 'sync_width',      20e-6,        's',  'SYNC pulse width (>= 20e-6)'; ...
 'ao_fs_V',         10.0,         'V',  'AO full-scale voltage: 10 (16-bit +-10/0-10 V with the panel divider) | 4.5 | 3.28 (no divider)'; ...
 'rearm_cmd',       0,            '-',  'ControlDesk re-arm (0 -> 1 edge; OR-ed with RE_ARM input)'; ...
 'run_enable',      1,            '-',  '1 run | 0 hold (states frozen, outputs held)'; ...
 'ao_pu_1',         2.64,         'pu', 'AO1 i_L full scale, x I_rated (feeder node clip)'; ...
 'ao_pu_2',         1.45,         'pu', 'AO2 v_bus full scale, x V_ref'; ...
 'ao_pu_3',         16.5,         'pu', 'AO3 i_rack full scale, x I_out_rated (rack node clip)'; ...
 'ao_pu_4',         1.45,         'pu', 'AO4 v_out full scale, x V_ref48'; ...
 'conv_smooth',     1,            '-',  'rack converter ramp-rate front end (MODEL.md 4.7 smooth_on): 1 on | 0 off; check (i) cases carry their own value'};

names = struct('fp', {fp(:, 1)'}, 'wp', {wp(:, 1)'}, 'cp', {cp(:, 1)'});
for grp = {fp, wp, cp}
    g = grp{1};
    for i = 1:size(g, 1)
        prm = Simulink.Parameter(g{i, 2});
        prm.CoderInfo.StorageClass = 'ExportedGlobal';
        prm.Unit = ''; prm.Description = sprintf('[%s] %s', g{i, 3}, g{i, 4});
        prm.DataType = 'double';
        assignin('base', g{i, 1}, prm);
    end
end
end
